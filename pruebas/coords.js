const { chromium } = require('/opt/node-tools/node_modules/playwright');
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 390, height: 844 } });
  const errs = [];
  p.on('pageerror', e => errs.push('PAGEERROR ' + e.message));
  p.on('console', m => { if (m.type()==='error') errs.push('console ' + m.text().slice(0,200)); });
  await p.goto('file://' + process.argv[2]); await p.waitForSelector('header.tv-header');
  await p.fill('input[placeholder^="Nombre de la nueva obra"]', 'Prueba'); await p.click('text=+ Crear obra');
  await p.fill('input[placeholder^="Nombre de la vía"]', 'Vía'); await p.click('text=+ Nueva vía');
  await p.fill('input[placeholder="ej. 965.390"]', '100');
  await p.fill('input[placeholder="ej. 964.840"]', '100.5');
  await p.click('text=Usar coordenadas');
  const N = () => p.$$('input[placeholder="Norte (Y)"]'), E = () => p.$$('input[placeholder="Este (X)"]');
  let n = await N(), e = await E();
  await n[0].fill('1000'); await e[0].fill('5000');
  await n[1].fill('1003'); await e[1].fill('5004');
  await p.click('text=+ Punto');
  n = await N(); e = await E();
  await n[2].fill('1009'); await e[2].fill('5012');
  console.log('lines:', JSON.stringify(await p.$$eval('td[colspan="4"]', t => t.map(x => x.innerText))));
  await p.click('text=/Pasar 2 distancia/');
  console.log('aviso:', await p.innerText('text=/✓/'));
  const dist = await p.$$eval('input[placeholder="ej. 27.5"]', i => i.map(x => x.value));
  const pend = await p.$$eval('input[placeholder="ej. -1.820"], input[placeholder$="0.000"], input[placeholder$="00"]', i => i.map(x => x.placeholder));
  console.log('distancias tramos:', JSON.stringify(dist));
  await p.fill('input[placeholder="ej. 964.840"] >> nth=1', '99.5');
  await p.click('button:has-text("CALCULAR")');
  const rows = await p.$$eval('table tbody tr', trs => trs.slice(0, 6).map(tr => tr.cells[0].innerText.replace(/\s+/g,' ') + ' | ' + tr.cells[1].innerText + ' | ' + tr.cells[4].innerText));
  console.log('tabla:', JSON.stringify(rows));
  await p.click('.tv-tabs button[data-tab=via]');
  await p.screenshot({ path: process.argv[3], fullPage: true });
  console.log(errs.join('\n') || 'no errors');
  await b.close();
})();
